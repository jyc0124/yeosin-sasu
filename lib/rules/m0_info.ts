export function judgeM0(c: M0Case, kb: KbVersion): Verdict {
  const t = TOPICS[c.topic];
  const card = new Card("M0", kb);
  // 규제지역 해제 질문에 지역이 나오면 그 지역으로 결론을 낸다(F813-01·F401-02: 대상은 '수도권 또는 규제지역' 아파트)
  if (c.topic === "regulated_area_change" && c.region) {
    const where = SIDO_FULL[c.region] ?? c.region;
    if (isCapital(c.region)) {
      card.step("M0 정보형", `${c.topic}: ${c.region} → 수도권`, ["F813-01", "F401-02"]);
      return card
        .cond(
          "비거주 1주택자에 해당하는지는 나머지 요건(부부합산 1주택, 임대 중, 본인·배우자 모두 실거주한 적 없음)으로 판단합니다.",
          "다주택자 주담대 만기연장 제한(4.1)도 수도권 아파트는 규제지역 해제와 관계없이 대상입니다.",
        )
        .done("불허", `${eun(where)} 수도권이라 규제지역에서 풀려도 비거주 1주택자 규제 대상 지역입니다. 대상은 수도권 아파트 전체와 수도권 밖 규제지역 아파트입니다.`);
    }
    card.step("M0 정보형", `${c.topic}: ${c.region} → 비수도권, 현재 규제지역 여부 확인 필요`, ["F813-01", "G-07"]);
    return card
      .latest()
      .done("보류", `${eun(where)} 수도권 밖이라 규제지역일 때만 대상입니다. 해제가 확정됐는지 최신 규제지역 지정 공고로 확인해야 합니다.`);
  }
  const facts = t.facts.filter((f) => kb === "v2" || !f.startsWith("F828"));
  // KB v1(보도자료·FAQ만)에서는 8.28 행정지도 기준(F828)이 없다 → 그 기준에 기대는 주제는 확정하지 않는다
  const fs = t.facts.filter((f) => !f.startsWith("G-"));
  const needs828 = fs.length > 0 && fs.every((f) => f.startsWith("F828"));
  if (kb === "v1" && needs828) {
    card.step("M0 정보형", `${c.topic}: 후속 지침(8.28 행정지도) 필요`, facts.length ? facts : ["F813-09"]);
    return card.latest().done("보류", "보도자료·FAQ에는 이 기준이 없습니다. 후속 지침 확인이 필요합니다.");
  }
  card.step("M0 정보형", c.topic, facts);
  for (const [label, text, fs] of t.basis ?? []) {
    const ok = fs.filter((f) => kb === "v2" || !f.startsWith("F828"));
    if (ok.length) card.basis(label, text, ok);
  }
  if (t.ask) card.ask(...t.ask);
  if (t.conditions) card.cond(...t.conditions);
  if (t.latest) card.latest();
  return card.done(t.verdict, t.headline);
}

