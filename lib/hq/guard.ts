// 질의서·회신 입력 점검: 개인정보(A은행 지침 제6조 2항), 규제 회피 안내(제7조 1항).
// 정규식 점검은 보조 수단이다. 사람이 확인하는 체크를 대신하지 않는다.

const PII: { label: string; re: RegExp }[] = [
  { label: "주민등록번호", re: /\d{6}\s*-?\s*[1-4]\d{6}/ },
  { label: "휴대전화 번호", re: /01[016789]\s*-?\s*\d{3,4}\s*-?\s*\d{4}/ },
  { label: "이메일", re: /[\w.+-]+@[\w-]+\.[\w.-]+/ },
  { label: "계좌번호로 보이는 숫자", re: /\d{3,6}-\d{2,6}-\d{4,8}/ },
];

/** 개인정보로 보이는 항목 종류(중복 없이) */
export function findPii(...texts: string[]): string[] {
  let t = texts.join("\n");
  const found: string[] = [];
  // 앞에서 찾은 값은 지우고 다음 패턴을 본다(전화번호가 계좌번호로 두 번 잡히지 않게)
  for (const p of PII) {
    const g = new RegExp(p.re.source, "g");
    if (g.test(t)) {
      found.push(p.label);
      t = t.replace(g, " ");
    }
  }
  return found;
}

// CLAUDE.md 원칙 4·A은행 지침 제7조 1항: 규제를 피하는 방법(조기 연장, 명의 분산, 계약일 조정 등)
const AVOIDANCE: { label: string; re: RegExp }[] = [
  { label: "조기·앞당긴 연장", re: /(조기|미리|앞당겨|당겨\s?두|당겨서|서둘러)\s?[^.]{0,12}(연장|신청|계약|갱신)/ },
  { label: "만기 전 연장", re: /만기\s?(전에|이전에|되기 전)[^.]{0,15}(연장|갱신|신청)(하시|해 두|해두|하면)/ },
  { label: "명의 이전·분산", re: /명의\s?(분산|이전|변경)|명의를?\s?(넘기|옮기|돌리|바꾸)|(가족|배우자|자녀)\s?명의로\s?(넘기|옮기|돌리|바꾸|하시)/ },
  { label: "증여로 주택 수 줄이기", re: /증여(하시|해\s?두|해 주)[^.]{0,20}(주택\s?수|빠지|제외)/ },
  { label: "계약일 조정", re: /(계약일|날짜|일자)(을|를)?\s?(조정|앞당|바꾸|맞추)/ },
  { label: "나눠 받기", re: /(쪼개|나눠|분할)[^.]{0,10}(받|신청|대출)/ },
  { label: "규제 회피", re: /규제를?\s?(피|회피|우회)|규제 회피/ },
  // 가정법으로 시점·날짜를 바꾸면 종전 규정·규제 미적용이 된다고 약속하는 문형(동사와 무관하게)
  // 예: "연장 시점을 12월로 옮기시면 종전 규정이 적용됩니다". 단 "증액하지 않으시면 종전 규정으로 심사"(규정 그대로)는 해당 없음
  {
    label: "조건부 회피 안내",
    re: /(시점|날짜|일자|만기일|기일|올해 ?안|연내|연말|이전으로|미리|먼저|앞당|당겨|옮기|변경|넣|\d{1,2}\s?월\s?(안|내|중|까지)|이번\s?달|지금|당장|접수하)[^.]{0,20}?[가-힣]*면[^.]{0,40}?(종전 규정(을|이|으로|대로)?\s?(적용|받|연장|심사)|규제(를|가)?\s?(안|피|적용되지 않|받지 않))/,
  },
];

/** 규제 회피 방법으로 읽힐 수 있는 표현(종류 이름) */
export function findAvoidance(text: string): string[] {
  const t = text.replace(/\s+/g, " ");
  return AVOIDANCE.filter((a) => a.re.test(t)).map((a) => a.label);
}
